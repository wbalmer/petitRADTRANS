"""JAXNS 3 over an asynchronous multi-node worker pool.
JAXNS 3 removed the device-sharded backend. Its replacement is an opt-in
worker runtime: a coordinator process (started with ``jaxns-cli up``) owns a
pool of worker processes, each pinned to one device, and the scientific
process submits constrained-sampling requests to it.

The runtime registers the model with each worker by cloudpickling a
``WorkerSession``. A pRT likelihood closes over the whole ``RetrievalRuntime``
-- including loaded opacity tables -- which cannot be shipped over the wire,
so this backend requires the prior model built by
:mod:`~petitRADTRANS.retrieval.samplers.jaxns_worker`, whose closure holds only
a small filesystem spec that each worker resolves and caches locally.

This module was generated by Claude to interface with JAXNS.
"""

import warnings
import gc
from petitRADTRANS.retrieval.samplers import _optional_imports as _opt
from petitRADTRANS.retrieval.samplers.base import SamplerContext
from petitRADTRANS.retrieval.samplers.jaxns import JAXNSSampler
from petitRADTRANS.retrieval.samplers.jaxns_worker import (
    build_distributed_prior_model,
)


class JAXNSDistributedSampler(JAXNSSampler):
    """Nested sampling with JAXNS 3 against a ``jaxns-cli`` worker pool."""

    sampler_type = "jaxns_distributed"
    aliases = ("jaxnsdistributed",)

    def __init__(
        self,
        log_likelihood_func,
        prior_func,
        output_directory,
        retrieval_name,
    ):
        super().__init__(
            log_likelihood_func, prior_func, output_directory, retrieval_name
        )
        _opt.require_jaxns_distributed()
        self.coordinator_port = 5555

    @classmethod
    def prepare(cls, context: SamplerContext, **sampler_kwargs):
        _opt.require_jaxns_distributed()

        coordinator_port = int(sampler_kwargs.pop("coordinator_port", 5555))
        spec_path = sampler_kwargs.pop("worker_spec_path", None)

        # The spec is written by the coordinator and read by every worker, so
        # it must live on shared storage. Default it next to the run outputs.
        free_parameter_names, prior_model, spec_path = build_distributed_prior_model(
            context, spec_path=spec_path
        )

        run_config = cls._resolve_run_config(sampler_kwargs)

        sampler = cls(
            log_likelihood_func=None,
            prior_func=prior_model,
            output_directory=context.output_directory,
            retrieval_name=context.retrieval_name,
        )
        sampler.parameter_names = list(free_parameter_names)
        sampler.offload_results_to_cpu = run_config["offload_results_to_cpu"]
        sampler.coordinator_port = coordinator_port

        summary_parameters = {
            "sampler_type": cls.sampler_type,
            "parameter_names": list(free_parameter_names),
            "seed": run_config["seed"],
            "coordinator_port": coordinator_port,
            "worker_spec_path": spec_path,
            "evidence_conditioning": run_config["evidence_conditioning"],
            "offload_results_to_cpu": run_config["offload_results_to_cpu"],
            **{
                key: value
                for key, value in run_config["nested_sampler_kwargs"].items()
                if value is not None
            },
        }
        if len(run_config["termination_summary"]) > 0:
            summary_parameters["termination_condition"] = run_config["termination_summary"]

        return sampler, {"run_config": run_config}, summary_parameters

    def _build_nested_sampler(self, model, run_config):
        nested_sampler_kwargs = {
            key: value
            for key, value in run_config["nested_sampler_kwargs"].items()
            if value is not None
        }
        # Distributed allocation has no shell width: one pending task is one
        # logical lineage thread, and per-worker batching is configured in the
        # worker TOML rather than here.
        for unsupported in ("shell_size", "batch_size"):
            if nested_sampler_kwargs.pop(unsupported, None) is not None:
                warnings.warn(
                    f"'{unsupported}' is ignored by the JAXNS distributed backend; "
                    "worker batching is configured per worker in the jaxns-cli TOML.",
                    RuntimeWarning,
                )

        slice_kwargs = dict(run_config["slice_sampler_kwargs"])
        slice_kwargs["collect_phantom_samples"] = nested_sampler_kwargs.get(
            "collect_phantom_samples", True
        )
        slice_sampler, slice_summary = self._build_slice_sampler(
            model, slice_kwargs, len(self.parameter_names)
        )
        if slice_sampler is not None:
            nested_sampler_kwargs["sampler"] = slice_sampler

        if run_config["termination_condition"] is not None:
            nested_sampler_kwargs["termination_condition"] = run_config[
                "termination_condition"
            ]

        self.jaxns_parameters = {
            **{
                key: value
                for key, value in nested_sampler_kwargs.items()
                if key not in ("sampler", "termination_condition")
            },
            **slice_summary,
            "coordinator_port": self.coordinator_port,
        }

        return _opt.DistributedNestedSampler(
            model=model,
            coordinator_port=self.coordinator_port,
            **nested_sampler_kwargs,
        )

    def _execute(self, run_config, checkpoint_dir):
        jax_random_key = _opt.random.PRNGKey(self.seed)
        goal_cond = run_config["goal_cond"]

        if goal_cond is None:
            # DistributedNestedSampler has no plain run(); its goal loop is the
            # only entry point, so mirror NestedSampler.run's default goal.
            def goal_cond(state):
                if int(state.goal_loop_iter) == 0:
                    return False
                done, _ = state.compute_termination_register().is_done(
                    self.sampler.termination_condition
                )
                return bool(done)

        return self.sampler.run_until_goal(
            goal_cond,
            key=jax_random_key,
            checkpoint_dir=checkpoint_dir,
            checkpoint_cadence=run_config["checkpoint_cadence"],
        )

    def _materialize_raw_results(self, state):
        # DistributedState.to_result() refuses while work is pending, and
        # returns the ordinary NestedSamplerResults otherwise.
        cpu_device = self._get_cpu_device()

        if cpu_device is None:
            return state.to_result().trim()

        state = _opt.device_get(state)
        gc.collect()
        _opt.clear_caches()

        with _opt.default_device(cpu_device):
            return state.to_result().trim()

