"""Worker-side model reconstruction for the JAXNS 3 distributed backend.

The JAXNS distributed runtime registers a scientific model with every worker
process by cloudpickling a ``WorkerSession`` that contains the
:class:`jaxns.model.Model` -- and therefore whatever the prior-model callable
closes over. cloudpickle makes it possible to serialize Python constructs not
supported by the default pickle module from the Python standard library.
cloudpickle is especially useful for cluster computing where Python code is
shipped over the network to execute on remote hosts, possibly close to the data.

A petitRADTRANS likelihood closes over a :class:`RetrievalRuntime`, which
transitively holds the ``Radtrans`` objects and their loaded opacity tables.
Those are gigabytes and are not meaningfully serialisable, so shipping that
closure over ZeroMQ is not an option.

Instead, the prior model built here closes over nothing but a **path to a small
JSON spec**. Every worker resolves that spec once, rebuilds its own
``RetrievalRuntime`` from the user's own module-level configuration factory,
and caches it for the lifetime of the process. Only the path crosses the wire.

This requires that

* the worker processes can import the module naming the factory, and
* the coordinator and the workers share a filesystem (true on Vera, and the
  same assumption the JAXNS runtime already makes for its runtime directory)

This module was generated by Claude to interface with JAXNS.
"""

import importlib
import json
import os
import threading
import time
from typing import Any

# Per-process cache of rebuilt runtimes, keyed by spec path. A worker handles
# many constrained-sampling requests, so the (expensive) opacity load and model
# construction must happen at most once per process.
_RUNTIME_CACHE: dict[str, tuple] = {}

# Guards _RUNTIME_CACHE. Without it the background pre-warm (below) and the
# REGISTER handler can rebuild the same spec concurrently, which means loading
# every opacity table twice in one process -- the exact cost this module exists
# to avoid.
_REBUILD_LOCK = threading.RLock()

#: Environment variable naming the worker spec to pre-warm at import.
PREWARM_ENVIRONMENT_VARIABLE = "PRT_JAXNS_WORKER_SPEC"

_PREWARM_THREAD: threading.Thread | None = None
_PREWARM_STARTED_AT: float | None = None


def _resolve_callable(target: str):
    """Import ``"package.module:function"`` and return the callable."""
    if ":" not in target:
        raise ValueError(
            f"Invalid factory reference {target!r}. Use 'package.module:function', "
            "naming a module-level function that the worker processes can import."
        )

    module_name, _, attribute_name = target.partition(":")

    try:
        module = importlib.import_module(module_name)
    except ImportError as error:
        raise ImportError(
            f"Worker could not import module {module_name!r} named by the JAXNS "
            "distributed configuration factory. Ensure the module is on PYTHONPATH in "
            "every worker process."
        ) from error

    try:
        return getattr(module, attribute_name)
    except AttributeError as error:
        raise AttributeError(
            f"Module {module_name!r} has no attribute {attribute_name!r} for the JAXNS "
            "distributed configuration factory."
        ) from error


def write_worker_spec(
    spec_path: str,
    config_factory: str,
    factory_kwargs: dict[str, Any],
    uncertainties_mode: str,
    free_parameter_names: list[str],
) -> str:
    """Write the small JSON spec that every worker resolves."""
    spec = {
        "config_factory": config_factory,
        "factory_kwargs": factory_kwargs,
        "uncertainties_mode": uncertainties_mode,
        "free_parameter_names": list(free_parameter_names),
    }
    os.makedirs(os.path.dirname(os.path.abspath(spec_path)), exist_ok=True)
    with open(spec_path, "w") as handle:
        json.dump(spec, handle, indent=4)
    return spec_path


def _rebuild(spec_path: str):
    """Rebuild ``(priors, parameter_layout, runtime)`` in this process, cached.

    Runs on the coordinator too, so a single-node distributed run exercises the
    same code path as a multi-node one.
    """
    cached = _RUNTIME_CACHE.get(spec_path)
    if cached is not None:
        return cached

    with _REBUILD_LOCK:
        # Re-check inside the lock: the pre-warm thread may have finished while
        # this caller was waiting for it.
        cached = _RUNTIME_CACHE.get(spec_path)
        if cached is not None:
            return cached
        return _rebuild_locked(spec_path)


def _rebuild_locked(spec_path: str):
    """The actual rebuild. Callers must hold ``_REBUILD_LOCK``."""
    with open(spec_path, "r") as handle:
        spec = json.load(handle)

    from petitRADTRANS.retrieval.runtime import ParameterLayout, RetrievalRuntime

    configuration = _resolve_callable(spec["config_factory"])(
        **spec.get("factory_kwargs", {})
    )

    # Mirrors Retrieval._get_parameter_layout / _get_runtime, so a worker
    # builds exactly the same objects the coordinator would.
    parameter_layout = ParameterLayout.from_configuration(configuration)
    runtime = RetrievalRuntime.from_configuration(
        configuration,
        parameter_layout=parameter_layout,
        n_free_parameters=parameter_layout.n_free_parameters,
    )

    expected_names = list(spec["free_parameter_names"])
    actual_names = list(parameter_layout.free_parameter_names)
    if actual_names != expected_names:
        # A worker silently rebuilding a *different* model would corrupt the
        # run in a way that is very hard to diagnose from the posterior alone.
        raise ValueError(
            "JAXNS distributed worker rebuilt a configuration whose free parameters "
            f"do not match the coordinator's. Expected {expected_names}, got "
            f"{actual_names}. The factory must be deterministic and version-matched "
            "across coordinator and workers."
        )

    priors = tuple(
        configuration.parameters[name].set_prior() for name in expected_names
    )

    rebuilt = (priors, parameter_layout, runtime, spec["uncertainties_mode"])
    _RUNTIME_CACHE[spec_path] = rebuilt
    return rebuilt


def prewarm(spec_path: str, *, background: bool = True) -> threading.Thread | None:
    """Rebuild the runtime for ``spec_path`` before any task needs it.

    The JAXNS coordinator kills a worker whose task exceeds ``task_timeout_s``,
    measuring from when the task was dispatched. A freshly restarted worker has
    an empty :data:`_RUNTIME_CACHE`, so its first task pays for loading every
    correlated-k table, constructing the Radtrans objects, and compiling the
    likelihood, which can take a significant amount of time.

    Pre-warming moves that cost off the task clock. Called in a daemon thread at
    import (see :func:`prewarm_from_environment`), the rebuild overlaps
    coordinator start-up and the arrival of the first task instead of being
    charged against it.

    It runs in the BACKGROUND rather than at import directly because the worker
    must complete its ZeroMQ handshake within ``startup_timeout_s`` (120 s by
    default) and begin heartbeating. Blocking the import would simply move the
    failure from the task timeout to the startup timeout.

    Args:
        spec_path: the worker spec written by :func:`write_worker_spec`.
        background: run in a daemon thread (default) or block until rebuilt.

    Returns:
        The thread when backgrounded, otherwise ``None``.
    """
    global _PREWARM_THREAD, _PREWARM_STARTED_AT

    if not background:
        _rebuild(spec_path)
        return None

    def _target():
        started = time.perf_counter()
        try:
            _rebuild(spec_path)
        except Exception as problem:                             # noqa: BLE001
            # A pre-warm failure must not kill the worker: the REGISTER path
            # will retry and raise there, where the coordinator can see it.
            print(f"[prt-jaxns] pre-warm of {spec_path} failed: "
                  f"{type(problem).__name__}: {problem}", flush=True)
            return
        print(f"[prt-jaxns] pre-warmed {spec_path} in "
              f"{time.perf_counter() - started:.1f} s", flush=True)

    _PREWARM_STARTED_AT = time.perf_counter()
    _PREWARM_THREAD = threading.Thread(
        target=_target, name="prt-jaxns-prewarm", daemon=True
    )
    _PREWARM_THREAD.start()
    return _PREWARM_THREAD


def prewarm_from_environment() -> threading.Thread | None:
    """Pre-warm if ``PRT_JAXNS_WORKER_SPEC`` names a readable spec.

    Worker processes are spawned by the JAXNS coordinator with
    ``environment = os.environ.copy()``, so a variable exported by the batch
    script reaches every worker. The spec path is deterministic --
    ``{output_directory}/out_JAXNS/{retrieval_name}_worker_spec.json`` -- so the
    batch script can name it before the coordinator has written it; a spec that
    does not exist yet is simply skipped, and the REGISTER path rebuilds as
    before.
    """
    spec_path = os.environ.get(PREWARM_ENVIRONMENT_VARIABLE)
    if not spec_path:
        return None
    if not os.path.exists(spec_path):
        print(f"[prt-jaxns] {PREWARM_ENVIRONMENT_VARIABLE}={spec_path} does not "
              "exist yet; skipping pre-warm", flush=True)
        return None
    return prewarm(spec_path)


class SpecBackedPriorModel:
    """A JAXNS 3 prior model that carries only a path to its rebuild spec.

    This is a module-level *class* rather than a closure on purpose. JAXNS
    pickles the model in two places -- the cloudpickled ``WorkerSession`` sent
    to distributed workers, and the ``State`` written to every checkpoint --
    and Python cannot pickle a function defined inside another function, no
    matter how small its closure. An instance of this class pickles as just
    ``(class, spec_path)``.

    That keeps the registration payload at kilobytes instead of gigabytes, and
    keeps ``jaxns.model._HashableCallable``'s content fingerprint (used for
    JIT-cache identity) cheap, since the instance's state is one short string.
    """

    __slots__ = ("spec_path", "__qualname__")

    # jaxns.model._HashableCallable fingerprints a prior model as if it were a
    # plain function (module, qualname, code object, defaults, closure cells)
    # to give the JIT cache a content-based identity. Expose those attributes
    # so a callable object is a drop-in: the code object is shared by every
    # instance, and __qualname__ carries the only thing that actually
    # distinguishes two of them.
    __closure__ = None
    __defaults__ = None
    __kwdefaults__ = None

    def __init__(self, spec_path: str):
        self.spec_path = spec_path
        self.__qualname__ = f"SpecBackedPriorModel[{spec_path}]"
        _rebuild(spec_path)

    @property
    def __code__(self):
        return type(self).__call__.__code__

    def __call__(self):
        cached = _RUNTIME_CACHE.get(self.spec_path)
        if cached is None:
            raise RuntimeError(
                "JAXNS worker runtime was not rebuilt before likelihood tracing. "
                "Construct SpecBackedPriorModel from its worker spec before "
                "registering the model."
            )
        priors, parameter_layout, runtime, uncertainties_mode = cached
        # Deliberately a plain loop, not a generator expression: JAXNS stores
        # this function's co_consts in its JIT-cache fingerprint, and a
        # comprehension would put a nested code object there, which pickle
        # cannot serialise -- breaking checkpointing and worker registration.
        values = []
        for prior, periodic in priors:
            values.append(prior.realise(periodic=periodic))
        values = tuple(values)
        physical_params = parameter_layout.physical_params_from_free_values(values)
        return runtime.evaluate_likelihood_jax(
            physical_params=physical_params,
            uncertainties_mode=uncertainties_mode,
            print_log_likelihood_for_debugging=False,
        )

    # Pickle/unpickle as the spec path alone; construction rebuilds and caches
    # the runtime before JAXNS starts tracing a likelihood program.
    def __reduce__(self):
        return (SpecBackedPriorModel, (self.spec_path,))

    def __eq__(self, other):
        return (
            isinstance(other, SpecBackedPriorModel)
            and other.spec_path == self.spec_path
        )

    def __hash__(self):
        return hash((SpecBackedPriorModel, self.spec_path))

    def __repr__(self):
        return f"SpecBackedPriorModel({self.spec_path!r})"


def distributed_prior_model(spec_path: str) -> SpecBackedPriorModel:
    """Return a picklable JAXNS 3 prior model backed by ``spec_path``."""
    return SpecBackedPriorModel(spec_path)


def build_distributed_prior_model(context, spec_path=None):
    """Build the worker-rebuildable prior model for a distributed JAXNS run.

    The configuration factory must be supplied on the retrieval configuration
    as ``jaxns_config_factory`` (a ``"package.module:function"`` string), with
    optional ``jaxns_config_factory_kwargs``. pRT cannot derive it: a
    ``RetrievalConfig`` holds live ``SpectralModel``/``Radtrans`` objects and
    user callables, so only the user knows how to rebuild it from scratch.

    Returns:
        ``(free_parameter_names, prior_model, spec_path)``.
    """
    from petitRADTRANS.retrieval.samplers.interfaces import collect_jaxns_priors

    free_parameter_names, _priors = collect_jaxns_priors(context)

    config_factory = getattr(context.configuration, "jaxns_config_factory", None)
    if config_factory is None:
        raise ValueError(
            "The JAXNS distributed backend needs to rebuild the retrieval inside each "
            "worker process, because the likelihood closes over opacity tables that "
            "cannot be shipped over the wire. Set "
            "`configuration.jaxns_config_factory = 'my_module:build_configuration'` to a "
            "module-level function (importable by the workers) that returns this same "
            "RetrievalConfig, plus optional "
            "`configuration.jaxns_config_factory_kwargs`."
        )

    factory_kwargs = dict(
        getattr(context.configuration, "jaxns_config_factory_kwargs", None) or {}
    )

    if spec_path is None:
        spec_path = os.path.join(
            context.output_directory,
            "out_JAXNS",
            f"{context.retrieval_name}_worker_spec.json",
        )
    spec_path = os.path.abspath(spec_path)

    write_worker_spec(
        spec_path=spec_path,
        config_factory=config_factory,
        factory_kwargs=factory_kwargs,
        uncertainties_mode=context.uncertainties_mode,
        free_parameter_names=free_parameter_names,
    )

    # Validate eagerly on the coordinator: an unimportable factory or a
    # mismatched parameter list should fail here, not inside a worker.
    _rebuild(spec_path)

    return free_parameter_names, distributed_prior_model(spec_path), spec_path


# Fires only when the batch script asks for it, so importing this module stays
# free for the coordinator and for anything that merely wants the helpers.
prewarm_from_environment()
